//Дано целое число A. Проверить истинность высказывания: «Число A является положительным»

#include <stdio.h>    // подключение библиотеки стандартного ввода-вывода (для работы с printf и scanf)
#include <stdbool.h>  // подключение библиотеки для работы с булевым типом bool (содержит значения true и false)

int main() {          // главная функция, с которой начинается выполнение программы
    int A;            // объявление целочисленной переменной A для хранения считываемого числа

    // функция scanf считывает целое число (%d) с клавиатуры
    // &A — оператор взятия адреса: передает адрес памяти переменной A, чтобы записать туда введенное значение
    scanf("%d", &A);

    // Вычисляется логическое выражение (A > 0):
    // если A больше 0, выражение возвращает true (истина)
    // если A меньше или равно 0, выражение возвращает false (ложь)
    // результат сохраняется в логическую переменную is_positive
    bool is_positive = (A > 0);

    // Конструкция условного перехода:
    if (is_positive) {
        // если is_positive равен true (число положительное), выводим "True"
        // \n — символ переноса строки
        printf("True\n");
    } else {
        // если is_positive равен false (число отрицательное или ноль), выводим "False"
        printf("False\n");
    }

    return 0;         // завершение работы программы с кодом 0 (сигнал ОС о том, что всё прошло успешно)
}