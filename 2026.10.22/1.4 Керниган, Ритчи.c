/* Кернгиан, Ритчи
Задание 1.4
Напишите программу для перевода температур по Цельсию в шкалу
Фаренгейта и вывода соответствующей таблицы. */

  #include <stdio.h>    // Подключение библиотеки стандартного ввода-вывода

int main() // Главная функция программы
{
    float fahr, celsius; // Объявление вещественных переменных для температур
    int lower, upper, step;

    lower = 0;    // Нижняя граница шкалы Цельсия
    upper = 300;  // Верхняя граница
    step = 20;    // Шаг изменения температуры

    celsius = lower;

    /* Вывод заголовка над таблицей */
    printf("Celsius  Fahr\n");
    printf("-------------\n");

    /* Цикл while для вычисления и вывода каждой строки таблицы */
    while (celsius <= upper) {
        /* Формула перевода из Цельсия в Фаренгейт: F = C * (9.0/5.0) + 32.0 */
        fahr = celsius * (9.0 / 5.0) + 32.0;
        
        /* Форматированный вывод:
           %6.0f — Цельсий в поле шириной 6 символов без знаков после запятой;
           %6.1f — Фаренгейт в поле шириной 6 символов с одним знаком после запятой. */
        printf("%6.0f %6.1f\n", celsius, fahr);
        
        /* Увеличение значения температуры на шаг */
        celsius = celsius + step;
    }

    return 0;
}