# 1. Ввод длин сторон прямоугольника и преобразование строки в целое число
a = int(input())
b = int(input())

# 2. Вычисление периметра по формуле P = 2 * (a + b)
P = 2 * (a + b)

# 3. Вычисление площади по формуле S = a * b
S = a * b

# 4. Вывод вычисленного значения площади на экран
print(S)
# 5. Вывод вычисленного значения периметра на экран
print(P)