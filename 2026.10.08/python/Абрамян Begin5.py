# 1. Ввод длины ребра куба и преобразование строки в целое число
a = int(input())


# 2. Вычисление объема куба по формуле V = a^3
V = pow(a, 3)

# 3. Вычисление площади поверхности куба по формуле S = 6 * a^2
S = 6 * pow(a, 2)

# 4. Вывод вычисленных значений объема и площади на экран
print(V)
print(S)
